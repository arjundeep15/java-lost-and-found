CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'STUDENT'
);
CREATE TABLE IF NOT EXISTS items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(120) NOT NULL, description TEXT,
 category VARCHAR(60) NOT NULL, item_status VARCHAR(20) NOT NULL, location_found VARCHAR(150),
 contact VARCHAR(120), image_name VARCHAR(100) NOT NULL DEFAULT 'notebook.svg', created_by BIGINT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_item_user FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);